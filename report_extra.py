"""Section 9 of the report: the items the previous version listed as unverified.

Numbers are read from the result files where they exist (crn6.json, refs2.json,
notmpl.json) so the table and the measurement cannot drift apart.
"""
import itertools, json, os
import numpy as np
from scipy.stats import pearsonr, spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
J = lambda n: json.load(open(os.path.join(HERE, n))) if os.path.exists(
    os.path.join(HERE, n)) else None
COORDS = ["α=1 raw", "α=1 norm", "α=0 √π"]
E = {"α=1 raw": "&alpha;=1 raw", "α=1 norm": "&alpha;=1 norm",
     "α=0 √π": "&alpha;=0 &radic;&pi;"}


def _corr(x, y):
    return pearsonr(x, y)[0], spearmanr(x, y)[0]


def _crn(A, tbl):
    d = J("crn6.json")
    if not d:
        return
    A('<h3>9.1 1回目を共有乱数でやり直す</h3>')
    A('<p>1回目の6つの LLM は、それぞれ別の乱数列からロールアウトを引いていた。'
      '同じ方策を持つ2体でも軌跡が食い違うので、挙動の距離に雑音の床ができる。'
      '2回目で使った共有乱数（タスクとステップごとに1つの一様乱数を全員で共有し、'
      '各エージェントの累積分布で逆変換する）で、8タスクを引き直した。</p>')
    rows = []
    for tag in ("共有乱数", "独立乱数（1回目）"):
        if tag not in d:
            continue
        B = d[tag]["behaviour"]
        for m in ("edit", "gram2", "first"):
            v = [B[k][m] for k in B]
            rows.append([tag, m, f"{min(v):.3f}", f"{np.median(v):.3f}",
                         f"{max(v):.3f}"])
    A(tbl(["乱数", "挙動の指標", "最小", "中央", "最大"], rows, numcols=(2, 3, 4),
          cap="15ペア。edit は正規化編集距離、gram2 は行動2連の Jaccard 非類似度、"
              "first は初手が違う割合。1.000 は共有する部分列がないこと。"))
    A('<div class="warn"><p><b>床を外しても、この6体では挙動の指標が飽和している。</b>'
      '共有乱数での中央値は edit 0.938 / gram2 0.968 で、最大は 1.000 に達する。'
      '6つの LLM の方策は、この環境で取りうるほど違っていて、'
      '<b>軌跡はほとんど何も共有しない。</b>比べる余地がないので、'
      '座標距離が挙動の距離を当てられるかという問いがそもそも立たない。</p></div>')
    rows = []
    B, K = d["共有乱数"]["behaviour"], d["共有乱数"]["sym_kl"]
    keys = list(B)
    for name, src in [(E[c], d["coord"][c]) for c in COORDS] + [("実測KL", K)]:
        for m in ("edit", "gram2"):
            r = spearmanr([src[k] for k in keys], [B[k][m] for k in keys])
            rows.append([name, m, f"{r[0]:.3f}", f"{r[1]:.3f}"])
    A(tbl(["近さの基準", "挙動の指標", "Spearman", "p"], rows, numcols=(2, 3),
          cap="共有乱数・15ペア。実測KL が最も当たる（edit 0.621、p=0.013）。"
              "その実測KL でさえ 0.62 にとどまるのが飽和の現れで、"
              "座標はどれも当たらない。"))
    A('<p>いっぽう、座標距離が<b>実測の軌跡KLそのもの</b>を当てるかは別の問いで、'
      'こちらは飽和しない。ロールアウトは各エージェント自身のものなので、'
      '参照のずれ &lambda; が最大限に効く条件である。</p>')
    rows = []
    for tag in ("共有乱数", "独立乱数（1回目）"):
        if tag not in d:
            continue
        K = d[tag]["sym_kl"]
        for c in COORDS:
            pe, sp = _corr([d["coord"][c][k] for k in keys], [K[k] for k in keys])
            rows.append([tag, E[c], f"{pe:.3f}", f"{sp:.3f}"])
    A(tbl(["乱数", "座標", "Pearson", "Spearman"], rows, numcols=(2, 3),
          cap="座標距離 対 各エージェント自身のロールアウト上の対称KL、15ペア。"))
    A('<div class="ok"><p><b>別々の LLM の集合でも、&alpha;=0 が一番よく追う'
      '（0.771 / 0.775 対 &alpha;=1 norm の 0.387 / 0.471、raw の 0.283 / 0.357）。</b>'
      '2回目のハーネス集合で出た順位が、1回目の設定でも同じ向きに出た。'
      'ただし水準そのものは低い。参照軌跡の上で測った座標が、'
      'エージェント自身が訪れる状態での違いを 0.77 までしか説明しないということで、'
      'これは埋め込みではなく &lambda; の寄与である。</p></div>')


def _refs(A, tbl):
    d = J("refs2.json")
    if not d or "A" not in d:
        return
    A('<h3>9.2 参照集合を替えると地図はどれだけ動くか（&lambda; の感度）</h3>')
    A('<p>座標は、誰も生成していない軌跡の上で読まれる。したがって地図は、'
      'その軌跡が通った場所でのみ方策を測っている。これが論文の &lambda; 項である。'
      '同じ9体を、作り方の違う3つの参照集合で測り直した。</p>')
    A(tbl(["参照集合", "作り方", "ステップ数"],
          [["setA", "オラクル12本 + 無作為12本、シード 0&ndash;23（元の集合）",
            str(d["A"]["M"])],
           ["setB", "同じ作り方、シード 5000&ndash;5023（集合の標本変動）",
            str(d.get("B", {}).get("M", "&mdash;"))],
           ["setC", "24本すべて無作為生成、シード 0&ndash;23（生成器のずれ）",
            str(d.get("C", {}).get("M", "&mdash;"))]], numcols=(2,)))
    keys = list(d["A"]["kl"])
    rows = []
    for t in sorted(d):
        for c in COORDS:
            pe, sp = _corr([d[t]["dist"][c][k] for k in keys],
                           [d[t]["kl"][k] for k in keys])
            rows.append([f"set{t}", E[c], f"{pe:.3f}", f"{sp:.3f}"])
    A(tbl(["参照集合", "座標", "Pearson", "Spearman"], rows, numcols=(2, 3),
          cap="各集合の上で、座標距離 対 その集合の状態での1ステップ対称KL（36ペア）。"
              "集合を替えても座標の順位は変わらない。"))
    rows = []
    for t in [x for x in sorted(d) if x != "A"]:
        for c in COORDS:
            a = np.array([d["A"]["dist"][c][k] for k in keys])
            b = np.array([d[t]["dist"][c][k] for k in keys])
            pe, sp = _corr(a, b)
            m = a > 0
            rows.append([f"setA 対 set{t}", E[c], f"{pe:.3f}", f"{sp:.3f}",
                         f"{np.median(b[m] / a[m]):.3f}"
                         + ("" if m.all() else f"（{int(m.sum())}組）")])
        a = np.array([d["A"]["kl"][k] for k in keys])
        b = np.array([d[t]["kl"][k] for k in keys])
        pe, sp = _corr(a, b)
        rows.append([f"setA 対 set{t}", "対称KL（実測）", f"{pe:.3f}", f"{sp:.3f}",
                     f"{np.median(b / a):.3f}"])
    A(tbl(["比較", "量", "Pearson", "Spearman", "距離の比（中央）"], rows,
          numcols=(2, 3, 4),
          cap="同じ36ペアを、2つの参照集合で測ったときの一致。"
              "比は set&times; &divide; setA。&alpha;=1 raw は温度だけが違う6組が"
              "距離 0 なので、比は残り30組で取った。"))
    import close, viz
    from scipy.spatial import procrustes
    N = close.NAMES
    rows = []
    for t in [x for x in sorted(d) if x != "A"]:
        for c in COORDS:
            X = []
            for src in (d["A"]["dist"][c], d[t]["dist"][c]):
                M = np.array([[0.0 if i == j else
                               src.get(f"{i}|{j}", src.get(f"{j}|{i}", 0.0))
                               for j in N] for i in N])
                X.append(viz.mds(M)[0])
            rows.append([f"setA 対 set{t}", E[c],
                         f"{procrustes(X[0], X[1])[2]:.3f}"])
    A(tbl(["比較", "座標", "Procrustes 不一致"], rows, numcols=(2,),
          cap="36ペアの距離を古典的MDSで2次元に落とし、"
              "回転・反転・拡大を最適に合わせた残差。0 なら同じ配置。"))
    A('<div class="ok"><p><b>&lambda; は水準には効くが、順位にはあまり効かない。</b>'
      '実測の対称KL そのものが集合を替えると中央値で 1.451 &rarr; 1.628 &rarr; 1.821 と'
      '最大 26% 動く。それでもペアの順位は Spearman 0.96&ndash;0.97 で保たれる。'
      '座標のうち<b>&alpha;=0 がいちばん集合に鈍い</b>: '
      'KL への追従が 0.983 / 0.989 / 0.988 と動かず、'
      '地図の食い違いは生成器を替えても 0.051（&alpha;=1 norm は 0.165）。'
      '<b>生成器のずれ（setC）は集合の標本変動（setB）より 2&ndash;3倍大きく'
      '地図を動かす。</b>参照軌跡を何本取るかより、'
      '何で生成するかのほうが効くということである。</p></div>')


