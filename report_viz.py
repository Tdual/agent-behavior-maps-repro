"""Section 8 of the report: the two-dimensional maps."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def _svg(name):
    return ('<div style="margin:14px 0 4px">'
            + open(os.path.join(HERE, "viz", name), encoding="utf-8").read()
            + '</div>')


def section(A, tbl):
    A('<h2>8. 2次元の地図</h2>')
    A('''<p>論文は100モデルの座標を t-SNE で平面に並べている。t-SNE は perplexity を
点の数より小さく取る必要があり、確率的でもあるので、9〜15体では使えない。ここでは距離行列から
<b>古典的MDS（主座標分析）</b>でも平面に落とす。決定論的で、2次元が元の配置をどれだけ保っているかを
数値で出せる。論文と同じ t-SNE も走らせ、両者を並べる。</p>''')
    A('''<p>2つの実験は<b>同じ参照軌跡193ステップ</b>を採点しているので、1枚の地図に載せられる。
整合性の確認として、<code>h4</code> と <code>qwen05-it</code> は定義上同一のエージェント
（同じ重み・窓4・同じ system プロンプト・温度1）であり、raw 座標の最大差は <b>0.000e+00</b> だった。
重複を除いた <b>14体</b>を1枚に置く。</p>''')

    A(tbl(["地図", "2次元が保つ割合", "Pearson", "Spearman"],
          [["14体・&alpha;=1 raw", "66.0%", "0.922", "0.929"],
           ["14体・&alpha;=1 norm", "63.6%", "0.908", "0.933"],
           ["14体・&alpha;=0 &radic;&pi;", "55.4%", "0.836", "0.885"],
           ["9体・&alpha;=1 norm", "73.4%", "0.953", "0.981"],
           ["9体・&alpha;=0 &radic;&pi;", "72.2%", "0.956", "0.923"]],
          numcols=(1, 2, 3),
          cap="Pearson / Spearman は、平面上の距離が元の距離をどれだけ再現しているか（Shepard 相関）。"))
    A('''<p><b>2次元は配置の 55〜73% しか保たない。</b> 論文の t-SNE 図も同じ性質を持つが、
論文は「近傍はすべて元の座標空間で計算した」「kNN は中心化座標のユークリッド距離を使う」と明記しており、
図は見るためのものと位置づけている。本節の地図も同じ扱いとする。</p>''')

    A('<h3>&alpha;=1 raw の地図: 盲点が目に見える</h3>')
    A(_svg("map14_raw.svg"))
    A('''<p class="caption">14エージェント。色は LLM の系列（左側）とハーネスの変更の種類（右側）。</p>''')
    A('''<p>温度だけが違う4体 <code>qwen05-it</code>・<code>h4-T0.9</code>・<code>h4-T1.1</code>・
<code>h4-T1.25</code> が<b>1点に重なる</b>。raw 座標は記録された行動の合計トークン対数尤度であり、
温度は許容集合上の正規化で効くので、この座標はそれを見られない。
重ねて描くと事実が隠れるので、同一点は併合して注記した。</p>''')

    A('<h3>論文と同じ t-SNE で落とす</h3>')
    A("""<p>論文は「Figure 1(a) is a t-SNE layout of the centered coordinates with
perplexity 15」と書いている。perplexity は点の数より小さくなければならないので、14体では15が使えない。
2から13まで全部走らせ、平面上の距離が元の距離の順位をどれだけ保つかで選んだ。</p>""")
    A(tbl(["perplexity", "距離の順位 Spearman", "perplexity", "距離の順位 Spearman"],
          [["2", "0.702", "8", "0.771"], ["3", "0.765", "9", "0.754"],
           ["4", "0.789", "10", "0.723"], ["5", "0.637", "11", "0.703"],
           ["<b>6</b>", "<b>0.865</b>", "12", "0.683"], ["7", "0.829", "13", "0.239"]],
          numcols=(1, 3),
          cap="14エージェント。最大の perplexity 13 では順位相関が 0.239 まで落ちる。"))
    A(_svg("tsne_14.svg"))
    A('<p class="caption">論文と同じ座標（&alpha;=1 raw・中心化）を t-SNE で平面に落としたもの。</p>')
    A("""<p><b>種による揺れは初期値の取り方で決まる。</b> PCA を初期値にすると
（scikit-learn の既定）、10種すべてで配置が完全に一致した（Procrustes 差 0.000）。
初期値を乱数にすると種で絵が変わり、perplexity を上げるほど激しくなる。</p>""")
    A(tbl(["初期値", "perplexity", "種どうしの Procrustes 差（中央値）", "最大"],
          [["PCA", "2&ndash;13 のすべて", "0.000", "0.000"],
           ["乱数", "3", "0.066", "0.120"], ["乱数", "6", "0.066", "0.216"],
           ["乱数", "9", "0.429", "0.775"], ["乱数", "12", "<b>0.641</b>", "<b>0.980</b>"]],
          numcols=(2, 3),
          cap="Procrustes 差は 0 が一致、1 が無関係。14体・10種・45組の値。"))
    A(tbl(["落とし方", "14体の距離の順位 Spearman", "6体"],
          [["t-SNE（最良の perplexity）", "0.865", "0.821"],
           ["古典的MDS", "<b>0.929</b>", "<b>0.975</b>"]], numcols=(1, 2),
          cap="同じ座標、同じ距離。t-SNE は距離を保つことを目的にしていないので、この差は想定どおり。"))

    A('<h3>論文 図1(a) と同じ設定: ハーネスを固定して LLM だけ変える</h3>')
    A(_svg("tsne_6.svg"))
    A("""<p>論文の図は100 LLM すべてが BASE ハーネスである。本再現で対応するのは
この6体だけの地図で、14体の地図は論文が一度も描いていない配置（2つの群の混在）になる。</p>""")
    A("""<p><b>同じ系列が隣り合わない。</b> SmolLM2 の3体は離れて置かれ、
<code>qwen05-it</code> と <code>qwen05</code>（同じ重みの instruct と base）は図の両端にある。
これは1回目の実験で挙動の近傍が再現できなかったこと（第2節・第10節）と同じ現象を見ている。</p>""")

    A('<h3>&alpha;=0 の地図: 同じ14体、別の配置</h3>')
    A(_svg("map14_a0.svg"))
    A('''<p class="caption">距離は Hellinger 距離 &radic;(mean 2(1&minus;BC))。温度の4体は分かれる。</p>''')

    A('<h3>LLM の違いとハーネスの違い、どちらが遠いか</h3>')
    A('''<p>地図を見ると、&alpha;=1 では6体の LLM が左に固まり、1 LLM のハーネス違い9体が大きく広がる。
&alpha;=0 では逆になる。どちらが正しいかは、同じ193ステップの上で
<b>1ステップあたりの対称KLを閉形式で</b>計算すれば決まる。ロールアウトは要らない。
全14体の許容行動すべてのスコアを取り直したので、この比較は全ペアで可能になった。</p>''')
    A(tbl(["量", "LLM 6体（15組）", "ハーネス9体（36組）", "LLM &divide; ハーネス"],
          [["座標距離 &alpha;=1 raw", "1.897", "2.622", "<b>0.72倍</b>"],
           ["座標距離 &alpha;=1 norm", "1.898", "2.309", "<b>0.82倍</b>"],
           ["座標距離 &alpha;=0 &radic;&pi;", "0.772", "0.525", "1.47倍"],
           ["1ステップ対称KL（同一状態・閉形式）", "<b>2.929</b>", "<b>1.451</b>", "<b>2.02倍</b>"]],
          numcols=(1, 2, 3), cap="すべて同じ193の参照状態の上での中央値。"))
    A('''<div class="warn"><p><b>&alpha;=1 の座標は、この2群の遠近を逆に並べる。</b>
実測KLでは LLM 同士のほうが 2.02倍 遠いのに、&alpha;=1 の座標距離では 0.72〜0.82倍、
つまりハーネス違いのほうが遠い側に出る。&alpha;=0 は 1.47倍 で向きが合う。</p></div>''')

    A('<h3>91ペア全体での順序づけ</h3>')
    A(tbl(["座標", "距離&sup2; と KL の Pearson", "順位の Spearman"],
          [["&alpha;=1 raw", "0.829", "0.815"],
           ["&alpha;=1 norm", "0.825", "0.787"],
           ["&alpha;=0 &radic;&pi;", "<b>0.985</b>", "<b>0.989</b>"]],
          numcols=(1, 2),
          cap="14体・91ペア。比較対象は同じ参照状態上の1ステップ対称KL。"))
    A('''<p>この比較が分離しているのは<b>埋め込みの誤差だけ</b>である。
参照分布と実際の行動分布のずれ（論文の &lambda;）は、座標の取り方を変えても消えないので、
両者に等しく残っている。&alpha;=0 が強いのは、参照が取った行動1個ではなく
方策全体を持っているためで、同じ前向き計算から得られる情報を捨てていないことによる。</p>''')
    A('''<p><b>2群を混ぜた地図では、&alpha;=1 の配置を距離として読んではいけない。</b>
論文自身が「誰と誰が似ているかには答えるが、どれだけ似ているかには答えない」と書いており、
また「異なる LLM の組が妥当域に入る保証はない」とも明記している。本節はその2点が
同時に効く場面を1枚の図にしたものである。</p>''')
